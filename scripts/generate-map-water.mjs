/**
 * Generate small, offline water geometries for the national map.
 * Source: Natural Earth 1:10m lakes and river/lake centerlines (public domain),
 * served as GeoJSON by the Natural Earth quick-start ArcGIS FeatureServer.
 * Run: node scripts/generate-map-water.mjs
 */
import { writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const out = resolve(dirname(fileURLToPath(import.meta.url)), "../src/cambodia-water.ts");
const service = "https://services.arcgis.com/0xnwbwUttaTjns4i/ArcGIS/rest/services/Natural_Earth_quick_start/FeatureServer";

async function query(layer, bbox) {
  const params = new URLSearchParams({
    where: "1=1", geometry: bbox, geometryType: "esriGeometryEnvelope",
    inSR: "4326", spatialRel: "esriSpatialRelIntersects",
    outFields: "name", outSR: "4326", f: "geojson",
  });
  const response = await fetch(`${service}/${layer}/query?${params}`);
  if (!response.ok) throw new Error(`Natural Earth query failed: ${response.status}`);
  const data = await response.json();
  if (!Array.isArray(data.features)) throw new Error("No GeoJSON features returned");
  return data.features;
}

function distance(point, a, b) {
  const dx = b[0] - a[0], dy = b[1] - a[1];
  const t = dx * dx + dy * dy === 0 ? 0 : Math.max(0, Math.min(1,
    ((point[0] - a[0]) * dx + (point[1] - a[1]) * dy) / (dx * dx + dy * dy)));
  return Math.hypot(point[0] - a[0] - t * dx, point[1] - a[1] - t * dy);
}

function simplify(points, epsilon) {
  if (points.length < 3) return points;
  let max = 0, index = -1;
  for (let i = 1; i < points.length - 1; i++) {
    const d = distance(points[i], points[0], points[points.length - 1]);
    if (d > max) { max = d; index = i; }
  }
  if (max <= epsilon) return [points[0], points[points.length - 1]];
  return simplify(points.slice(0, index + 1), epsilon).slice(0, -1)
    .concat(simplify(points.slice(index), epsilon));
}

const lakes = await query(85, "103,12,105,14");
const lake = lakes.find((feature) => feature.properties.name === "Tonlé Sap");
if (!lake || lake.geometry.type !== "Polygon") throw new Error("Tonlé Sap polygon not found");
const shore = lake.geometry.coordinates[0];
const shoreOpen = shore[0][0] === shore.at(-1)[0] && shore[0][1] === shore.at(-1)[1]
  ? shore.slice(0, -1) : shore;

const rivers = await query(11, "102,10,108,15");
const tonle = rivers.find((feature) => feature.properties.name === "Tonle Sap" && feature.geometry.type === "LineString");
const mekong = rivers.find((feature) => feature.properties.name === "Mekong" && feature.geometry.type === "MultiLineString");
if (!tonle || !mekong) throw new Error("Tonlé Sap or Mekong centerline not found");
// The Natural Earth Mekong has separate upstream and delta branches. Keep the
// connected Cambodian main course; trim where it crosses the national border.
const main = mekong.geometry.coordinates.find((line) =>
  line.some((p) => p[1] > 14.8) && line.some((p) => p[1] < 11.7));
const delta = mekong.geometry.coordinates.find((line) =>
  line.some((p) => p[1] < 10.1) && line.some((p) => p[1] > 11.5));
if (!main || !delta) throw new Error("Mekong Cambodian segments not found");
const mekongPath = main.filter((p) => p[1] <= 14.5)
  .concat(delta.filter((p) => p[1] >= 10.9).toReversed());

const round = (points) => points.map(([lng, lat]) => [Math.round(lat * 1e5) / 1e5, Math.round(lng * 1e5) / 1e5]);
const emit = (name, points, epsilon) => {
  const closed = name.startsWith("TONLE_SAP_LAKE");
  const source = closed ? points.concat([points[0]]) : points;
  const simplified = simplify(source, epsilon);
  if (closed) simplified.pop();
  return `export const ${name}: [number, number][] = ${JSON.stringify(round(simplified))};`;
};
const text = `// AUTO-GENERATED by scripts/generate-map-water.mjs. Do not hand-edit.
// Natural Earth 1:10m lakes and rivers (public domain). Coordinates [lat,lng].
// These are generalized map geometries, not navigational or flood-season data.
${emit("TONLE_SAP_LAKE_NORMAL", shoreOpen, 0.025)}
${emit("TONLE_SAP_LAKE_ULTRA", shoreOpen, 0.005)}
${emit("TONLE_SAP_RIVER_NORMAL", tonle.geometry.coordinates, 0.022)}
${emit("TONLE_SAP_RIVER_ULTRA", tonle.geometry.coordinates, 0.004)}
${emit("MEKONG_NORMAL", mekongPath, 0.022)}
${emit("MEKONG_ULTRA", mekongPath, 0.004)}
`;
writeFileSync(out, text);
console.log(`Wrote ${out}: ${shoreOpen.length} shoreline points, ${tonle.geometry.coordinates.length} Tonlé Sap river points, ${mekongPath.length} Mekong points before simplification.`);
