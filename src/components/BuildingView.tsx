/**
 * A single **building's page** — the building on its own, turning slowly on a
 * paved apron, with its name, what it is for, and how it is built. Opened by
 * tapping the building in the site scene.
 *
 * Same three view modes as everywhere else: Normal for a low-end phone, Ultra
 * for a capable one, and VR (which always presents Ultra).
 */
type ViewMode = "normal" | "ultra";

function detectViewMode(): ViewMode {
  if (typeof navigator === "undefined") return "ultra";
  const cores = navigator.hardwareConcurrency ?? 4;
  const mem = (navigator as Navigator & { deviceMemory?: number }).deviceMemory ?? 4;
  const small = typeof window !== "undefined" && Math.min(window.screen.width, window.screen.height) < 500;
  return cores <= 4 || mem <= 3 || small ? "normal" : "ultra";
}

/** One paving tile-set per 8 m of ground → roughly 1 m slabs. */
const PAVER_M = 8;

const PALM_LOOK: PlantLook = { form: "palm", leaf: "#3f8a44", leaf2: "#57a052", bark: "#9a7b4a" };

/**
 * Palm trees flanking the NUM Monument on this page: 2 rows of 4 on each
 * side (16 total), same layout as the live campus (see `monumentPalms` in
 * BuildingsView.tsx) but centred on the origin since the building page
 * always renders its landmark at [0, 0, 0].
 */
const MONUMENT_PALMS = (() => {
  const rowOffsets = [10, 14];
  const zOffsets = [-6, -2, 2, 6];
  const list: { pos: [number, number, number]; spin: number }[] = [];
  for (const side of [-1, 1]) {
    rowOffsets.forEach((rowOffset, li) => {
      zOffsets.forEach((zOffset, zi) => {
        list.push({ pos: [side * rowOffset, 0, zOffset], spin: (li * 4 + zi) * 1.3 });
      });
    });
  }
  return list;
})();

/**
 * A building generated by `scripts/generate-building.mjs` from a JSON spec —
 * the no-3D-skills route in docs/BUILDINGS.md. Landmarks are hand-authored
 * components instead; this is for ordinary blocks, where fifteen numbers and a
 * photograph are the whole contribution.
 */
function GeneratedBuilding({ model }: { model: string }) {
  const { scene } = useGLTF(`/models/${model}.glb`);
  const copy = useMemo(() => {
    const c = scene.clone(true);
    c.traverse((o) => { o.castShadow = true; o.receiveShadow = true; });
    return c;
  }, [scene]);
  return <primitive object={copy} />;
}

/**
 * Draw just this building, centred on the origin — at the same size it stands
 * on the campus. Sizes come from `campusLayout.ts` rather than being typed
 * again here, so a page can't quietly show a different building from the one
 * you just walked up to.
 */
function TheBuilding({ id, model, onRoomClick }: { id: string; model?: string; onRoomClick?: (r: string) => void }) {
  if (model) return <GeneratedBuilding model={model} />;
  const parts = membersOf(id);
  const dims = (layoutId: string): [number, number] => {
    const b = layoutById(layoutId);
    return b ? sizeOf(b) : [10, 10];
  };
  switch (id) {
    case "hall": {
      const [w, d] = dims("hall");
      return <GreatHall position={[0, 0, 0]} w={w} d={d} />;
    }
    case "teaching": {
      const [w, d] = dims("teaching");
      return <TeachingBlock position={[0, 0, 0]} w={w} d={d} floors={4} onRoomClick={onRoomClick} />;
    }
    // Two separate structures on the way in: the gate down at the public road,
    // and the name sign where the avenue reaches the campus. Each page shows
    // its own — previously "gate" rendered the monument, so the Main Entrance
    // page disagreed with the place its own landmark button walked you to.
    case "gate": return <MainGate position={[0, 0, 0]} rotation={Math.PI} />;
    case "monument": return <EntranceMonument position={[0, 0, 0]} rotation={0} />;
    case "shrine": return <Shrine position={[0, 0, 0]} />;
    case "construction": {
      const [w, d] = dims("construction");
      return <ConstructionBlock position={[0, 0, 0]} w={w} d={d} floors={5} />;
    }
    case "parking": {
      // Laid out left-to-right in the order they stand on the ground, keeping
      // their real spacing so the page shows the actual car park.
      const xs = parts.map((p) => p.position[0]);
      const mid = (Math.min(...xs) + Math.max(...xs)) / 2;
      return (
        <>
          {parts.map((p) => {
            const [len, wid] = sizeOf(p);
            return (
              <ParkingCanopy
                key={p.id}
                position={[p.position[0] - mid, 0, 0]}
                rotation={Math.PI / 2}
                length={len}
                width={wid}
              />
            );
          })}
        </>
      );
    }
    case "field": {
      const [w, d] = dims("field");
      return <SportsField position={[0, 0, 0]} w={w} d={d} />;
    }
    case "sport-bathroom": {
      const [w, d] = dims("teaching-block-khmgey");
      return <TeachingBlock position={[0, 0, 0]} w={w} d={d} floors={1} tower={false} />;
    }
    case "west-gate": return <MainGate position={[0, 0, 0]} rotation={Math.PI} />;
    case "pool": {
      const [w, d] = dims("pool-ani4gy");
      // The same excavated basin the campus shows — not a flat rectangle. This
      // page turns the model on a turntable, so a single plane would flatten
      // out and change appearance through every revolution.
      //
      // Sat ON the apron rather than sunk into it: this page has no hole cut in
      // its ground, so a sunken basin would be hidden under the paving and you
      // would see only the lip of the coping.
      return <Pool w={w} d={d} topY={POOL.depth} />;
    }
    default: return null;
  }
}

function CameraAnimator({ room, aim, dist, eye }: { room: string | null; aim: number; dist: number; eye: number }) {
  const { camera } = useThree();
  const controls = useThree((s) => s.controls) as any;
  const done = useRef(false);

  let tx = 15;
  let ty = 1.5;
  
  if (room === 'admin') tx = -15;
  else if (room === 'middle') tx = 0;
  else if (room === 'camboverse') tx = 15;
  else if (room && (room.startsWith('class-') || room.startsWith('office-'))) {
    const parts = room.split('-'); // e.g. ['office', '2', '4']
    const fIdx = parseInt(parts[1], 10);
    const bayIdx = parseInt(parts[2], 10);
    const roomW = 60 / 7;
    tx = -30 + roomW / 2 + bayIdx * roomW;
    ty = 1.5 + fIdx * 3.5; // elevated by floor count
  }

  // Stand just inside the room's front wall (z≈6.9) and look in and slightly
  // down toward the back (z=-4), rather than pivoting on the spot at z=5. The old
  // spot dropped you right on top of the waiting-area furniture, so a dark table
  // filled the lower half of the view and read as a black floor. From here the
  // whole room reads and nothing sits against the lens.
  const posVec = useMemo(() => room ? new Vector3(tx, ty + 0.4, 6.9) : new Vector3(dist * 0.5, eye, dist), [room, tx, ty, dist, eye]);
  const targetVec = useMemo(() => room ? new Vector3(tx, ty - 0.4, -4) : new Vector3(0, aim, 0), [room, tx, ty, aim]);

  useEffect(() => {
    done.current = false;
    if (controls) {
      controls.enabled = false;
      // Failsafe: force re-enable after 1.5s in case lerp gets stuck
      const timer = setTimeout(() => {
        done.current = true;
        controls.enabled = true;
      }, 1500);
      return () => clearTimeout(timer);
    }
  }, [room, controls]);

  useFrame(() => {
    if (!controls || done.current) return;
    
    controls.target.lerp(targetVec, 0.08);
    camera.position.lerp(posVec, 0.08);
    controls.update();

    if (camera.position.distanceTo(posVec) < 0.2) {
      done.current = true;
      controls.enabled = true; // hand back control
    }
  });

  return null;
}

export function BuildingView({
  building,
  initialRoom = null,
  onRoomChange,
  onBack,
  onBackToMap,
  backLabel = "← Back",
}: {
  building: Building;
  initialRoom?: string | null;
  onRoomChange?: (room: string | null) => void;
  onBack: () => void;
  onBackToMap: () => void;
  /**
   * A building page is reached either from its site or straight from the
   * Buildings directory, so the caller names the step back rather than this
   * guessing and getting it wrong half the time.
   */
  backLabel?: string;
}) {
  const store = useMemo(() => createXRStore({ emulate: false }), []);
  const [vrSupported, setVrSupported] = useState(false);
  const [mode, setMode] = useState<ViewMode>(detectViewMode);
  // We initialize spin based on whether a room was pre-selected.
  const [spin, setSpin] = useState(!initialRoom);
  // The info sheet is most of a phone screen, and the building is the point of
  // the page. It opens by default — you arrive wanting to know what this is —
  // but it has to get out of the way in one tap.
  const [info, setInfo] = useState(true);
  const [room, _setRoom] = useState<string | null>(initialRoom);

  const setRoom = (r: string | null) => {
    _setRoom(r);
    onRoomChange?.(r);
  };

  useEffect(() => {
    const xr = (navigator as Navigator & { xr?: { isSessionSupported(m: string): Promise<boolean> } }).xr;
    xr?.isSessionSupported("immersive-vr").then(setVrSupported).catch(() => setVrSupported(false));
  }, []);

  // Frame from the footprint, not just the height — a long low block needs far
  // more room than a tall narrow one. Keep the eye low so we read the facade
  // rather than the roof, and aim high so the info sheet doesn't cover it.
  //
  // The distance has to come off the *horizontal* field of view, which on a
  // portrait phone is far narrower than the 45° vertical one: at a 0.64 aspect
  // it is only ~29°. Sizing off height alone put a 62 m building half outside
  // the frame on a phone while looking fine on a laptop.
  const dist = useMemo(() => {
    const aspect = Math.min(2.2, Math.max(0.45, window.innerWidth / window.innerHeight));
    const halfV = Math.tan((45 * Math.PI) / 360);
    const halfH = Math.atan(halfV * aspect);
    const forSpan = (building.spanM * 0.5) / Math.tan(halfH) * 1.12;
    const forHeight = (building.heightM * 0.6) / halfV;
    return Math.max(forSpan, forHeight, 26);
  }, [building.spanM, building.heightM]);
  const eye = Math.max(4, building.heightM * 0.5);
  // The orbit target lands at the centre of the viewport, so everything ABOVE it
  // in world space draws above centre. Aiming high therefore pushes the building
  // DOWN the screen, straight behind the info sheet — the opposite of what the
  // old comment here claimed. Aim low while the sheet is open so the building
  // sits in the clear band above it, and re-centre when the sheet is dismissed.
  const aim = Math.max(2.5, building.heightM * (info ? 0.34 : 0.5));

  return (
    <div className="building">
      <Canvas
        dpr={mode === "normal" ? [1, 1.5] : [1, 2]}
        camera={{ position: [dist * 0.5, eye, dist], fov: 45, near: 0.5, far: 900 }}
        gl={{ antialias: mode === "ultra", powerPreference: "high-performance" }}
        shadows={mode === "ultra"}
        onCreated={({ gl }) => {
          gl.toneMapping = ACESFilmicToneMapping;
          gl.toneMappingExposure = 1.15;
        }}
      >
        <XR store={store}>
          <Sky sunPosition={[120, 70, 60]} turbidity={5} rayleigh={1} mieCoefficient={0.005} mieDirectionalG={0.92} />
          <fog attach="fog" args={["#cfe0e8", 200, 700]} />
          <ambientLight intensity={0.55} />
          <hemisphereLight args={["#cfe2ff", "#6b8a45", 0.8]} />
          <directionalLight
            position={[80, 70, 50]}
            intensity={2.3}
            color="#fff1d6"
            castShadow={mode === "ultra"}
            shadow-mapSize={[2048, 2048]}
            shadow-bias={-0.0006}
            shadow-camera-far={300}
            shadow-camera-left={-90}
            shadow-camera-right={90}
            shadow-camera-top={90}
            shadow-camera-bottom={-90}
          />
          <Ground />
          <TheBuilding id={building.id} model={building.model} onRoomClick={(r) => { setRoom(r); setSpin(false); }} />
          <CameraAnimator room={room} aim={aim} dist={dist} eye={eye} />
          {/* a pair of palms for scale, hidden for teaching block, hall, and
              field to avoid clipping, and for the monument which has its own
              dedicated flanking palms below. */}
          {building.id !== "teaching" && building.id !== "hall" && building.id !== "field"
            && building.id !== "monument" && [-1, 1].map((s) => (
            <group key={s} position={[s * (dist * 0.42), 0, dist * 0.18]}>
              <PalmPlant look={PALM_LOOK} height={11} seed={s + 3} opacity={1} wind={mode === "ultra" ? 1 : 0} />
            </group>
          ))}
          {/* palm trees flanking the monument, matching the live campus layout */}
          {building.id === "monument" && MONUMENT_PALMS.map((p, i) => (
            <Palm key={`mon-palm-${i}`} position={p.pos} scale={1.15} spin={p.spin} />
          ))}
          {/* VR locomotion: left thumbstick walks, right thumbstick snap-turns.
              XROrigin starts behind the building so you face it on entry.
              Works on any WebXR device, optimised for Meta Quest 3. */}
          <VRRig position={[0, 0, dist * 0.8]} />
          <VrImpliesUltra onEnter={() => setMode("ultra")} />
          <OrbitControls
            makeDefault
            enablePan={false}
            minDistance={0.1}
            maxDistance={dist * 2.6}
            maxPolarAngle={Math.PI / 2.12}
            enableDamping
            autoRotate={spin}
            autoRotateSpeed={0.5}
          />
        </XR>
      </Canvas>

      <div className="cls-top">
        <button className="backbtn" onClick={() => {
          if (room) {
            setRoom(null);
          } else {
            onBack();
          }
        }}>
          {room ? "← Building" : backLabel}
        </button>
        <span className="cls-title">🏛️ {building.name}</span>
        <button
          className="grove-quality"
          onClick={() => setMode((m) => (m === "ultra" ? "normal" : "ultra"))}
          title="View mode — Normal is the low-end baseline, Ultra is the full 3D scene"
        >
          {mode === "ultra" ? "✨ Ultra" : "🍃 Normal"}
        </button>
        <button
          className="vr-btn cls-vr"
          style={!vrSupported ? { opacity: 0.45, cursor: "not-allowed" } : undefined}
          title={vrSupported ? "Enter VR — works on Meta Quest 3 and any WebXR headset" : "VR not detected — open this page on a Meta Quest browser or connect a headset via Air Link"}
          onClick={() => { if (vrSupported) { setMode("ultra"); store.enterVR(); } }}
        >
          🥽 VR
        </button>
      </div>

      <button className="bld-spin" onClick={() => setSpin((v) => !v)}>
        {spin ? "⏸ Stop turning" : "▶ Turn"}
      </button>

      {!info && (
        <button className="bld-show" onClick={() => setInfo(true)}>
          ℹ️ About this building
        </button>
      )}

      <div className={`bld-panel${info ? "" : " bld-panel--hidden"}`} aria-hidden={!info}>
        <div className="bld-head">
          <b>{building.name}</b>
          <span className="khmer">{building.khmer}</span>
          <button
            className="bld-hide"
            onClick={() => setInfo(false)}
            aria-label="Hide the description and see the building"
            title="Hide"
          >
            ✕
          </button>
        </div>
        <div className="bld-sub">
          {building.english}{building.site ? ` · ${building.site}` : ""}
        </div>
        {building.about.map((p) => (
          <p key={p.slice(0, 24)} className="bld-about">{p}</p>
        ))}
        <ul className="bld-facts">
          {building.facts.map((f) => (
            <li key={f.label}><span>{f.label}</span><b>{f.value}</b></li>
          ))}
        </ul>
        <p className="bld-note">
          Modelled from photographs of the real building — the massing is an informed
          approximation, not survey data. Corrections welcome.
        </p>
        <div className="bld-actions">
          {room && <button className="bld-map" onClick={() => setRoom(null)}>← Zoom out</button>}
          <button className="bld-map" onClick={onBackToMap}>← Back to the map</button>
          <button className="bld-hide-btn" onClick={() => setInfo(false)}>Hide</button>
        </div>
      </div>
    </div>
  );
}

function Ground() {
  const grass = useMemo(() => grassTexture(30), []);
  const pave = useMemo(() => paveTexture(metresRepeat(156, 156, PAVER_M)[0]), []);
  return (
    <>
      <mesh rotation={[-Math.PI / 2, 0, 0]} position={[0, -0.06, 0]} receiveShadow>
        <planeGeometry args={[900, 900]} />
        <meshStandardMaterial map={grass} roughness={1} />
      </mesh>
      {/* the apron sits over the lawn — offset so the two can't fight for depth */}
      <mesh rotation={[-Math.PI / 2, 0, 0]} position={[0, 0.01, 0]} receiveShadow>
        <circleGeometry args={[78, 48]} />
        <meshStandardMaterial
          map={pave} roughness={1}
          polygonOffset polygonOffsetFactor={-1} polygonOffsetUnits={-1}
        />
      </mesh>
    </>
  );
}

function VrImpliesUltra({ onEnter }: { onEnter: () => void }) {
  const inXR = useXR((s) => s.session != null);
  useEffect(() => { if (inXR) onEnter(); }, [inXR, onEnter]);
  return null;
}
